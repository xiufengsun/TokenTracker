-- InsForge remains authoritative while clients run both cloud backends.
-- Keep the final committed representation of each touched usage key until
-- Cloudflare acknowledges the exact revision. The device API never reads this table.
CREATE SCHEMA IF NOT EXISTS tokentracker_private;

CREATE TABLE IF NOT EXISTS tokentracker_private.cloudflare_usage_outbox (
  relation text NOT NULL,
  row_key jsonb NOT NULL,
  user_id uuid,
  device_id uuid,
  revision bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  row_data jsonb,
  PRIMARY KEY (relation, row_key)
);

CREATE INDEX IF NOT EXISTS cloudflare_usage_outbox_device
  ON tokentracker_private.cloudflare_usage_outbox (user_id, device_id, revision);

REVOKE ALL ON tokentracker_private.cloudflare_usage_outbox FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION tokentracker_private.capture_cloudflare_usage()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog AS $$
DECLARE
  data jsonb;
  previous jsonb;
  identity_columns text[];
  data_columns text[];
  counters CONSTANT text[] := ARRAY['input_tokens','cached_input_tokens','cache_creation_input_tokens',
    'output_tokens','reasoning_output_tokens','total_tokens'];
  timestamp_column text;
  counter_column text;
  key_before jsonb;
  key_after jsonb;
  owner_before uuid;
  owner_after uuid;
BEGIN
  IF TG_TABLE_NAME = 'tokentracker_hourly' THEN
    identity_columns := ARRAY['user_id', 'device_id', 'source', 'model', 'hour_start'];
    data_columns := counters || ARRAY['billable_total_tokens','conversations','created_at',
      'updated_at','total_cost_usd','cost_coverage'];
  ELSIF TG_TABLE_NAME = 'tokentracker_account_session_states' THEN
    identity_columns := ARRAY['user_id', 'source', 'session_id'];
    data_columns := counters || ARRAY['model','bucket_start','snapshot_verified_at','updated_at'];
  ELSIF TG_TABLE_NAME = 'tokentracker_devices' THEN
    identity_columns := ARRAY['id'];
    data_columns := ARRAY['user_id','device_name','platform','machine_id','revoked_at',
      'name_customized','default_device_name','created_at','last_seen_at'];
  ELSIF TG_TABLE_NAME = 'tokentracker_device_machine' THEN
    identity_columns := ARRAY['device_id'];
    data_columns := ARRAY['machine_cluster_id'];
  ELSIF TG_TABLE_NAME = 'tokentracker_device_tokens' THEN
    identity_columns := ARRAY['id'];
    data_columns := ARRAY['user_id','device_id','token_hash','revoked_at','created_at',
      'cloud_environment','last_used_at','last_sync_at'];
  ELSE
    RAISE EXCEPTION 'Unsupported usage relation %', TG_TABLE_NAME;
  END IF;

  IF TG_OP <> 'INSERT' THEN previous := to_jsonb(OLD); END IF;
  IF TG_OP <> 'DELETE' THEN data := to_jsonb(NEW); END IF;
  IF previous IS NOT NULL THEN
    SELECT jsonb_object_agg(key,value) INTO previous FROM jsonb_each(previous)
    WHERE key=ANY(identity_columns || data_columns);
  END IF;
  IF data IS NOT NULL THEN
    SELECT jsonb_object_agg(key,value) INTO data FROM jsonb_each(data)
    WHERE key=ANY(identity_columns || data_columns);
  END IF;
  IF data = previous THEN RETURN NULL; END IF;

  -- Match the full snapshot's fixed-width UTC representation. Capture integers
  -- and decimals as text so the Workers JSON boundary preserves all digits.
  FOREACH timestamp_column IN ARRAY ARRAY[
    'hour_start', 'bucket_start', 'snapshot_verified_at', 'created_at', 'updated_at',
    'revoked_at', 'last_seen_at', 'last_used_at', 'last_sync_at'
  ] LOOP
    IF previous ->> timestamp_column IS NOT NULL THEN
      previous := jsonb_set(previous, ARRAY[timestamp_column], to_jsonb(
        to_char((previous ->> timestamp_column)::timestamptz AT TIME ZONE 'UTC',
                'YYYY-MM-DD"T"HH24:MI:SS.US"Z"')
      ));
    END IF;
    IF data ->> timestamp_column IS NOT NULL THEN
      data := jsonb_set(data, ARRAY[timestamp_column], to_jsonb(
        to_char((data ->> timestamp_column)::timestamptz AT TIME ZONE 'UTC',
                'YYYY-MM-DD"T"HH24:MI:SS.US"Z"')
      ));
    END IF;
  END LOOP;
  FOREACH counter_column IN ARRAY ARRAY[
    'input_tokens', 'cached_input_tokens', 'cache_creation_input_tokens',
    'output_tokens', 'reasoning_output_tokens', 'total_tokens',
    'billable_total_tokens', 'conversations', 'total_cost_usd'
  ] LOOP
    IF data ->> counter_column IS NOT NULL THEN
      data := jsonb_set(data, ARRAY[counter_column], to_jsonb(data ->> counter_column));
    END IF;
  END LOOP;
  IF TG_TABLE_NAME = 'tokentracker_devices' AND data IS NOT NULL THEN
    data := jsonb_set(data, '{name_customized}', to_jsonb(coalesce((data->>'name_customized')::boolean, false)::int));
  END IF;
  IF data ->> 'cost_coverage' IS NOT NULL THEN
    data := jsonb_set(data, '{cost_coverage}', to_jsonb(data ->> 'cost_coverage'));
  END IF;

  owner_before := (previous->>'user_id')::uuid;
  owner_after := (data->>'user_id')::uuid;
  IF TG_TABLE_NAME = 'tokentracker_device_machine' THEN
    SELECT d.user_id INTO owner_before FROM public.tokentracker_devices d WHERE d.id=(previous->>'device_id')::uuid;
    SELECT d.user_id INTO owner_after FROM public.tokentracker_devices d WHERE d.id=(data->>'device_id')::uuid;
  END IF;
  IF previous IS NOT NULL THEN
    SELECT jsonb_agg(previous -> column_name ORDER BY position)
    INTO key_before FROM unnest(identity_columns) WITH ORDINALITY AS c(column_name, position);
  END IF;
  IF data IS NOT NULL THEN
    SELECT jsonb_agg(data -> column_name ORDER BY position)
    INTO key_after FROM unnest(identity_columns) WITH ORDINALITY AS c(column_name, position);
  END IF;

  IF key_before IS NOT NULL AND key_before IS DISTINCT FROM key_after THEN
    INSERT INTO tokentracker_private.cloudflare_usage_outbox(relation,row_key,user_id,device_id)
    VALUES (TG_TABLE_NAME,key_before,owner_before,(CASE WHEN TG_TABLE_NAME = 'tokentracker_devices' THEN previous->>'id' ELSE previous->>'device_id' END)::uuid)
    ON CONFLICT (relation,row_key) DO UPDATE SET revision=excluded.revision,
      user_id=excluded.user_id,device_id=excluded.device_id,row_data=NULL;
  END IF;
  IF key_after IS NOT NULL THEN
    INSERT INTO tokentracker_private.cloudflare_usage_outbox(relation,row_key,user_id,device_id,row_data)
    VALUES (TG_TABLE_NAME,key_after,owner_after,(CASE WHEN TG_TABLE_NAME = 'tokentracker_devices' THEN data->>'id' ELSE data->>'device_id' END)::uuid,data)
    ON CONFLICT (relation,row_key) DO UPDATE SET revision=excluded.revision,
      user_id=excluded.user_id,device_id=excluded.device_id,row_data=excluded.row_data;
  END IF;
  RETURN NULL;
END
$$;

REVOKE ALL ON FUNCTION tokentracker_private.capture_cloudflare_usage() FROM PUBLIC, anon, authenticated;

