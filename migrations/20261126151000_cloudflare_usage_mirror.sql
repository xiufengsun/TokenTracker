CREATE OR REPLACE FUNCTION public.tokentracker_cloudflare_usage_pending(
  p_device_token_hash text, p_limit integer
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog AS $$
DECLARE
  owner_id uuid;
  machine_id uuid;
BEGIN
  IF p_device_token_hash IS NOT NULL THEN
    SELECT t.user_id,t.device_id INTO owner_id,machine_id
    FROM public.tokentracker_device_tokens AS t
    WHERE t.token_hash=p_device_token_hash AND t.revoked_at IS NULL;
    IF owner_id IS NULL THEN RETURN jsonb_build_object('authorized',false); END IF;
  END IF;
  RETURN jsonb_build_object('authorized',true,'events',coalesce((
    SELECT jsonb_agg(jsonb_build_object(
      'revision',r.revision::text,'relation',r.relation,'key',r.row_key,'row',r.row_data
    ) ORDER BY r.revision) FROM (
      SELECT * FROM tokentracker_private.cloudflare_usage_outbox
      WHERE (owner_id IS NULL OR user_id=owner_id AND (device_id IS NULL OR device_id=machine_id))
      -- A newly issued token can only be applied after its parent device.
      ORDER BY (relation = 'tokentracker_devices') DESC,revision LIMIT greatest(1,least(p_limit,100))
    ) AS r
  ),'[]'::jsonb));
END
$$;

CREATE OR REPLACE FUNCTION public.tokentracker_cloudflare_usage_ack(p_revisions bigint[])
RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = pg_catalog AS $$
  DELETE FROM tokentracker_private.cloudflare_usage_outbox WHERE revision = ANY(p_revisions);
$$;

REVOKE ALL ON FUNCTION public.tokentracker_cloudflare_usage_pending(text,integer) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.tokentracker_cloudflare_usage_ack(bigint[]) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.tokentracker_cloudflare_usage_pending(text,integer) TO project_admin;
GRANT EXECUTE ON FUNCTION public.tokentracker_cloudflare_usage_ack(bigint[]) TO project_admin;
