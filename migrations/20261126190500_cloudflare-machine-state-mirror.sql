-- Keep device slot admission and upload leases current during the parallel rollout.
SET LOCAL lock_timeout = '2s';

CREATE TABLE tokentracker_private.cloudflare_machine_outbox (
  relation text NOT NULL CHECK (relation IN ('tokentracker_cloud_machines','tokentracker_cloud_machine_aliases')),
  row_key jsonb NOT NULL,
  user_id uuid NOT NULL,
  revision bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  row_data jsonb,
  PRIMARY KEY (relation,row_key)
);
CREATE INDEX cloudflare_machine_outbox_owner ON tokentracker_private.cloudflare_machine_outbox(user_id,revision);
REVOKE ALL ON tokentracker_private.cloudflare_machine_outbox FROM PUBLIC, anon, authenticated;

CREATE FUNCTION tokentracker_private.cloudflare_machine_key(p_relation text, p_row jsonb)
RETURNS jsonb LANGUAGE sql IMMUTABLE SET search_path = pg_catalog AS $$
  SELECT CASE p_relation
    WHEN 'tokentracker_cloud_machines' THEN jsonb_build_array(p_row->'id')
    WHEN 'tokentracker_cloud_machine_aliases' THEN
      jsonb_build_array(p_row->'user_id',p_row->'environment',p_row->'kind',p_row->'alias')
  END;
$$;

CREATE FUNCTION tokentracker_private.queue_cloudflare_machine(p_relation text, p_row jsonb, p_delete boolean)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE
  event_key jsonb := tokentracker_private.cloudflare_machine_key(p_relation, p_row);
  row_data jsonb;
  col text;
BEGIN
  IF event_key IS NULL THEN RAISE EXCEPTION 'Unsupported machine relation'; END IF;
  IF NOT p_delete THEN
    IF p_relation = 'tokentracker_cloud_machines' THEN
      SELECT jsonb_object_agg(key,value) INTO row_data FROM jsonb_each(p_row)
      WHERE key IN ('id','user_id','environment','status','merged_into','created_at','last_seen_at',
                    'last_upload_at','upload_window_until','upload_token_id','upload_id','upload_batch_count');
      FOREACH col IN ARRAY ARRAY['created_at','last_seen_at','last_upload_at','upload_window_until'] LOOP
        IF row_data->>col IS NOT NULL THEN
          row_data := jsonb_set(row_data,ARRAY[col],to_jsonb(to_char(
            (row_data->>col)::timestamptz AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.US"Z"')));
        END IF;
      END LOOP;
    ELSE
      SELECT jsonb_object_agg(key,value) INTO row_data FROM jsonb_each(p_row)
      WHERE key IN ('user_id','environment','kind','alias','machine_id');
    END IF;
  END IF;
  INSERT INTO tokentracker_private.cloudflare_machine_outbox(relation,row_key,user_id,row_data)
  VALUES(p_relation,event_key,(p_row->>'user_id')::uuid,row_data)
  ON CONFLICT (relation,row_key) DO UPDATE SET revision=excluded.revision,
    user_id=excluded.user_id,row_data=excluded.row_data;
END;
$$;

CREATE FUNCTION tokentracker_private.capture_cloudflare_machine()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
BEGIN
  IF TG_OP='UPDATE' AND to_jsonb(OLD)=to_jsonb(NEW) THEN RETURN NULL; END IF;
  IF TG_OP='DELETE' OR (TG_OP='UPDATE' AND
    tokentracker_private.cloudflare_machine_key(TG_TABLE_NAME,to_jsonb(OLD)) IS DISTINCT FROM
    tokentracker_private.cloudflare_machine_key(TG_TABLE_NAME,to_jsonb(NEW))) THEN
    PERFORM tokentracker_private.queue_cloudflare_machine(TG_TABLE_NAME,to_jsonb(OLD),true);
  END IF;
  IF TG_OP<>'DELETE' THEN
    PERFORM tokentracker_private.queue_cloudflare_machine(TG_TABLE_NAME,to_jsonb(NEW),false);
  END IF;
  RETURN NULL;
END;
$$;

REVOKE ALL ON FUNCTION tokentracker_private.cloudflare_machine_key(text,jsonb) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION tokentracker_private.queue_cloudflare_machine(text,jsonb,boolean) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION tokentracker_private.capture_cloudflare_machine() FROM PUBLIC, anon, authenticated;

CREATE TRIGGER cloudflare_usage_outbox AFTER INSERT OR UPDATE OR DELETE ON public.tokentracker_cloud_machines
FOR EACH ROW EXECUTE FUNCTION tokentracker_private.capture_cloudflare_machine();
CREATE TRIGGER cloudflare_usage_outbox AFTER INSERT OR UPDATE OR DELETE ON public.tokentracker_cloud_machine_aliases
FOR EACH ROW EXECUTE FUNCTION tokentracker_private.capture_cloudflare_machine();

CREATE FUNCTION public.tokentracker_cloudflare_machine_pending(
  p_device_token_hash text, p_limit integer
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE
  owner_id uuid;
BEGIN
  IF p_device_token_hash IS NOT NULL THEN
    SELECT t.user_id INTO owner_id
    FROM public.tokentracker_device_tokens AS t
    WHERE t.token_hash=p_device_token_hash AND t.revoked_at IS NULL;
    IF owner_id IS NULL THEN RETURN jsonb_build_object('authorized',false); END IF;
  END IF;
  RETURN jsonb_build_object('authorized',true,'events',coalesce((
    SELECT jsonb_agg(jsonb_build_object(
      'revision',r.revision::text,'relation',r.relation,'key',r.row_key,'row',r.row_data
    ) ORDER BY r.revision) FROM (
      SELECT q.* FROM tokentracker_private.cloudflare_machine_outbox q
      WHERE (owner_id IS NULL OR q.user_id=owner_id)
        AND (
            -- A newly created slot must commit before any alias or merged slot references it.
            q.row_data IS NOT NULL AND NOT EXISTS (
              SELECT 1 FROM tokentracker_private.cloudflare_machine_outbox parent
              WHERE parent.relation='tokentracker_cloud_machines' AND parent.row_data IS NOT NULL
                AND parent.row_key=jsonb_build_array(CASE q.relation
                  WHEN 'tokentracker_cloud_machines' THEN q.row_data->'merged_into'
                  ELSE q.row_data->'machine_id' END)
            ) OR q.row_data IS NULL AND (
              q.relation='tokentracker_cloud_machine_aliases' OR NOT EXISTS (
                -- Resolve alias moves, removals and merged-slot updates before a slot deletion.
                SELECT 1 FROM tokentracker_private.cloudflare_machine_outbox child
                WHERE child.user_id=q.user_id AND (
                  child.relation='tokentracker_cloud_machine_aliases' OR
                  child.relation='tokentracker_cloud_machines' AND child.row_data IS NOT NULL)
              )
            )
        )
      ORDER BY q.revision
      LIMIT greatest(1,least(p_limit,100))
    ) AS r
  ),'[]'::jsonb));
END;
$$;

CREATE FUNCTION public.tokentracker_cloudflare_machine_ack(p_revisions bigint[])
RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = pg_catalog AS $$
  DELETE FROM tokentracker_private.cloudflare_machine_outbox WHERE revision=ANY(p_revisions);
$$;
REVOKE ALL ON FUNCTION public.tokentracker_cloudflare_machine_pending(text,integer) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.tokentracker_cloudflare_machine_ack(bigint[]) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.tokentracker_cloudflare_machine_pending(text,integer) TO project_admin;
GRANT EXECUTE ON FUNCTION public.tokentracker_cloudflare_machine_ack(bigint[]) TO project_admin;

-- Capture the few thousand current slot rows while the triggers hold the schema locks.
-- Usage and device token history already has its own verified baseline.
DO $$ BEGIN
  PERFORM tokentracker_private.queue_cloudflare_machine('tokentracker_cloud_machines',to_jsonb(m),false)
  FROM public.tokentracker_cloud_machines m;
  PERFORM tokentracker_private.queue_cloudflare_machine('tokentracker_cloud_machine_aliases',to_jsonb(a),false)
  FROM public.tokentracker_cloud_machine_aliases a;
END $$;
